
import 'dart:convert';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:flutter/material.dart';

class IncidentReportScreen extends StatelessWidget {
  final Map<String, dynamic> incident;

  const IncidentReportScreen({
    super.key,
    required this.incident,
  });


Future<void> generatePdfReport() async {
  final status =
      (incident['status'] ?? 'UNKNOWN').toString();

  final detectedAt =
      (incident['detected_at'] ?? 'Unknown time').toString();

  final incidentId =
      (incident['id'] ?? 'N/A').toString();

  List violations = [];

  try {
    final raw = incident['violations'];

    if (raw is List) {
      violations = raw;
    } else if (raw is String && raw.isNotEmpty) {
      final decoded = jsonDecode(raw);
      if (decoded is List) {
        violations = decoded;
      }
    }
  } catch (_) {
    violations = [];
  }

  final pdf = pw.Document();

  pdf.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(36),
      build: (context) => [
        pw.Center(
          child: pw.Text(
            'INDUSTRIAL SAFETY INCIDENT REPORT',
            style: pw.TextStyle(
              fontSize: 19,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
        ),
        pw.SizedBox(height: 8),
        pw.Divider(),
        pw.SizedBox(height: 16),

        pw.Text(
          'Incident Information',
          style: pw.TextStyle(
            fontSize: 16,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
        pw.SizedBox(height: 10),

        pw.Text('Incident ID: $incidentId'),
        pw.SizedBox(height: 6),
        pw.Text('Detection Time: $detectedAt'),
        pw.SizedBox(height: 6),
        pw.Text('Safety Status: $status'),

        pw.SizedBox(height: 24),

        pw.Text(
          'PPE Detection Details',
          style: pw.TextStyle(
            fontSize: 16,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
        pw.SizedBox(height: 10),

        if (violations.isEmpty)
          pw.Text('No violation details available.')
        else
          pw.TableHelper.fromTextArray(
            headers: [
              'S.No.',
              'Detected Class',
              'Confidence',
            ],
            data: [
              for (int i = 0; i < violations.length; i++)
                [
                  '${i + 1}',
                  violations[i] is Map
                      ? (violations[i]['class'] ?? 'Unknown')
                          .toString()
                          .replaceAll('-', ' ')
                          .toUpperCase()
                      : 'Unknown',
                  violations[i] is Map
                      ? '${(((violations[i]['confidence'] as num?)?.toDouble() ?? 0.0) * 100).toStringAsFixed(1)}%'
                      : 'N/A',
                ],
            ],
          ),

        pw.SizedBox(height: 24),
        pw.Divider(),
        pw.Text(
          'Generated by AI Industrial Safety Monitoring System',
          style: const pw.TextStyle(fontSize: 10),
        ),
      ],
    ),
  );

  await Printing.layoutPdf(
    onLayout: (format) async => pdf.save(),
    name: 'Incident_Report_$incidentId.pdf',
  );
}

  @override
  Widget build(BuildContext context) {
    final status =
        (incident['status'] ?? 'UNKNOWN').toString();

    final detectedAt =
        (incident['detected_at'] ?? 'Unknown time')
            .toString();

    final id = incident['id']?.toString() ?? 'N/A';

    List violations = [];

    try {
      final raw = incident['violations'];

      if (raw is List) {
        violations = raw;
      } else if (raw is String && raw.isNotEmpty) {
        final decoded = jsonDecode(raw);
        if (decoded is List) {
          violations = decoded;
        }
      }
    } catch (_) {
      violations = [];
    }

    final isViolation = status == 'SAFETY VIOLATION';

    return Scaffold(
      appBar: AppBar(
        title: const Text('Detailed Incident Report'),
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Card(
              child: Padding(
                padding: const EdgeInsets.all(18),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Text(
                      'Incident Information',
                      style: TextStyle(
                        fontSize: 20,
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                    const SizedBox(height: 16),
                    _detailRow('Incident ID', id),
                    _detailRow('Detection Time', detectedAt),
                    _detailRow('Safety Status', status),
                    _detailRow(
                      'Total Detected Violations',
                      violations.length.toString(),
                    ),
                  ],
                ),
              ),
            ),
            const SizedBox(height: 16),
            Card(
              child: Padding(
                padding: const EdgeInsets.all(18),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Text(
                      'PPE Detection Details',
                      style: TextStyle(
                        fontSize: 20,
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                    const SizedBox(height: 12),
                    if (violations.isEmpty)
                      const Text(
                        'No violation details available.',
                      )
                    else
                      ...violations.map((item) {
                        if (item is! Map) {
                          return const SizedBox.shrink();
                        }

                        final name = (item['class'] ?? 'Unknown')
                            .toString()
                            .replaceAll('-', ' ')
                            .toUpperCase();

                        final confidence =
                            (item['confidence'] as num?)
                                    ?.toDouble() ??
                                0.0;

                        return ListTile(
                          contentPadding: EdgeInsets.zero,
                          leading: Icon(
                            isViolation
                                ? Icons.warning_amber_rounded
                                : Icons.check_circle,
                            color: isViolation
                                ? Colors.red
                                : Colors.green,
                          ),
                          title: Text(name),
                          subtitle: Text(
                            'Confidence: '
                            '${(confidence * 100).toStringAsFixed(1)}%',
                          ),
                        );
                      }),
                  ],
                ),
              ),
            ),
            const SizedBox(height: 16),
            Card(
              color: isViolation
                  ? Colors.red.shade50
                  : Colors.green.shade50,
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Row(
                  children: [
                    Icon(
                      isViolation
                          ? Icons.warning
                          : Icons.check_circle,
                      color: isViolation
                          ? Colors.red
                          : Colors.green,
                    ),
                    const SizedBox(width: 12),
                    Expanded(
                      child: Text(
                        isViolation
                            ? 'Safety violation recorded. '
                                'Review the detected PPE issues.'
                            : 'No safety violation was recorded '
                                'for this inspection.',
                      ),
                    ),
                  ],
                ),
              ),
            ),
            const SizedBox(height: 20),

SizedBox(
  width: double.infinity,
  child: ElevatedButton.icon(
    onPressed: generatePdfReport,
    icon: const Icon(Icons.picture_as_pdf),
    label: const Text('Download / Print PDF Report'),
    style: ElevatedButton.styleFrom(
      padding: const EdgeInsets.all(16),
      backgroundColor: Colors.indigo,
      foregroundColor: Colors.white,
    ),
  ),
),
          ],
        ),
      ),
    );
  }

  Widget _detailRow(String label, String value) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          SizedBox(
            width: 145,
            child: Text(
              label,
              style: const TextStyle(
                fontWeight: FontWeight.w600,
              ),
            ),
          ),
          Expanded(child: Text(value)),
        ],
      ),
    );
  }
}
